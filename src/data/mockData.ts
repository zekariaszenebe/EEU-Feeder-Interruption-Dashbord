const getPastHoursString = (hours: number): string => {
  const d = new Date();
  d.setMinutes(d.getMinutes() - Math.round(hours * 60));
  return d.toLocaleString('en-US', {
    month: 'short',
    day: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
    hour12: true
  });
};

const getFutureHoursString = (hours: number): string => {
  const d = new Date();
  d.setMinutes(d.getMinutes() + Math.round(hours * 60));
  return d.toLocaleString('en-US', {
    month: 'short',
    day: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
    hour12: true
  });
};

